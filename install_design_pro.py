def dec(b): return gzip.decompress(base64.b64decode(''.join(b.split())))

def main():
    here = os.getcwd()
    app = os.path.join(here, 'phone-app')
    idx = os.path.join(app, 'index.html'); sty = os.path.join(app, 'style.css')
    if not (os.path.isfile(idx) and os.path.isfile(sty) and os.path.isfile(os.path.join(app, 'design.js'))):
        print('ERROR: I do not see phone-app/index.html, style.css and design.js here.')
        print('Open Terminal and run:  cd ~/Downloads/jobber-clone   then run this again.')
        sys.exit(1)
    html = open(idx, encoding='utf-8').read(); css = open(sty, encoding='utf-8').read()
    if 'design-data.js' not in html or 'design.js' not in html:
        print('ERROR: index.html does not look like the FieldBase design page. Nothing was changed.'); sys.exit(1)
    bdir = os.path.expanduser('~/Downloads/fieldbase-backup-' + time.strftime('%Y%m%d-%H%M%S'))
    os.makedirs(bdir, exist_ok=True)
    shutil.copy2(idx, os.path.join(bdir, 'index.html')); shutil.copy2(sty, os.path.join(bdir, 'style.css'))
    print('Backed up index.html and style.css to', bdir)
    for name, blob in FILES.items():
        with open(os.path.join(app, name), 'wb') as fh: fh.write(dec(blob))
        print('  wrote phone-app/' + name)
    # scripts that exist on disk right now (so a later package is never referenced before it is installed)
    present = [s for s in ALL_SCRIPTS if os.path.isfile(os.path.join(app, s))]
    new_html = patch_index(html, present)
    new_css = patch_css(css, dec(CSS).decode('utf-8'))
    open(idx, 'w', encoding='utf-8').write(new_html)
    open(sty, 'w', encoding='utf-8').write(new_css)
    # verify
    h = open(idx, encoding='utf-8').read(); c = open(sty, encoding='utf-8').read()
    ok = all(('src="%s?v=' % s) in h for s in present) and 'design-data-pro.js' in h and CSS_START in c and CSS_END in c
    order = [h.index('src="%s?v=' % s) for s in ['design.js'] + [p for p in present]]
    ok = ok and order == sorted(order)
    print()
    print('Scripts added to index.html:', ', '.join(['design-data-pro.js'] + present))
    print('RESULT:', 'ALL GOOD' if ok else 'SOMETHING LOOKS WRONG - send me a screenshot of this window')
    print()
    print('Next: open GitHub Desktop, commit the changes, and push. Then in about 2 minutes open the app in a private window.')
    sys.exit(0 if ok else 2)

main()
