import re, os
NEWVER = '20261201a'
ALL_SCRIPTS = ['design-pro.js','design-checks.js','design-lighting.js','design-3d.js','design-photo.js','design-share.js']
CSS_START = '/* DESIGN-PRO-PATCH-START */'
CSS_END = '/* DESIGN-PRO-PATCH-END */'

def patch_index(html, scripts_after_design):
    # bump cache-busting version on every asset link
    html = re.sub(r'\?v=\d{8}[a-z]', '?v=' + NEWVER, html)
    # data file right after design-data.js
    tag_data = '<script src="design-data-pro.js?v=%s"></script>' % NEWVER
    if 'design-data-pro.js' not in html:
        m = re.search(r'<script src="design-data\.js\?v=[^"]*"></script>', html)
        assert m, 'design-data.js script tag not found'
        html = html[:m.end()] + '\n  ' + tag_data + html[m.end():]
    # remove any earlier copies of our add-on scripts, then add them all back in order
    for s in ALL_SCRIPTS:
        html = re.sub(r'\n[ \t]*<script src="%s\?v=[^"]*"></script>' % re.escape(s), '', html)
    m = re.search(r'<script src="design\.js\?v=[^"]*"></script>', html)
    assert m, 'design.js script tag not found'
    add = ''.join('\n  <script src="%s?v=%s"></script>' % (s, NEWVER) for s in scripts_after_design)
    html = html[:m.end()] + add + html[m.end():]
    return html

def patch_css(css, block):
    block = CSS_START + '\n' + block.strip() + '\n' + CSS_END
    if CSS_START in css:
        a = css.index(CSS_START); b = css.index(CSS_END) + len(CSS_END)
        return css[:a] + block + css[b:]
    return css.rstrip() + '\n\n' + block + '\n'


